import { randomBytes } from 'node:crypto';
import type { IRequestContext } from "src/core/application/contracts/infrastructure";
import type { IWebhookEndpointsRepository } from "src/core/application/contracts/persistence/webhook-endpoint.repository";
import { ActionNotAllowedException } from "src/core/domain/exceptions";
import { UseCase, UseCaseArgs } from "src/core/domain/models";
import type { RegisterWebhookEndpointInput } from "./register-webhook-endpoint.request-data";

export interface WebhookEndpointSecretDTO {
    id_client: number;
    endpoint_uuid: string;
    url: string;
    is_active: boolean;
    /** The raw secret, returned exactly once: never listed again. */
    secret: string;
    created_at: Date | null;
}

export class RegisterWebhookEndpointUseCase implements UseCase<RegisterWebhookEndpointInput, WebhookEndpointSecretDTO> {
    constructor(
        private readonly _context: IRequestContext,
        private readonly _webhookEndpointsRepository: IWebhookEndpointsRepository,
    ) { }

    public run = async (args: UseCaseArgs<RegisterWebhookEndpointInput>): Promise<WebhookEndpointSecretDTO> => {
        const auth = this._context.get();
        const authIsAdmin = auth?.is_admin === true;

        let id_client: bigint;
        const requested = args.data.id_client;
        if (requested !== undefined && requested !== null) {
            if (!authIsAdmin) {
                throw new ActionNotAllowedException('Solo un administrador puede registrar webhooks para otro cliente');
            }
            id_client = BigInt(requested);
        } else {
            if (auth === null || auth === undefined) {
                throw new ActionNotAllowedException('Sesion no valida para registrar webhooks');
            }
            id_client = BigInt(auth!.id_user);
        }

        // A secret is not a uuid: it is generated code-side from raw entropy.
        const secret = randomBytes(32).toString('hex');

        // endpoint_uuid is never sent: the uuid is generated by the database
        // (gen_random_uuid) and the created row comes back carrying it.
        const created = await this._webhookEndpointsRepository.create({
            id_client,
            url: args.data.url,
            secret,
            is_active: true,
        });

        return {
            id_client: Number(created.id_client),
            endpoint_uuid: created.endpoint_uuid,
            url: created.url,
            is_active: created.is_active,
            secret: created.secret,
            created_at: created.created_at,
        };
    };
}
