import type { IRequestContext } from "src/core/application/contracts/infrastructure";
import type { ITemplatesRepository } from "src/core/application/contracts/persistence";
import type { TemplateInfoDTO } from "src/core/application/dtos";
import { ActionNotAllowedException } from "src/core/domain/exceptions";
import { UseCase, UseCaseArgs } from "src/core/domain/models";
import { TemplateMapper } from "src/core/application/mappers";
import { CreateTemplateInput } from "./create-template.request-data";

export class CreateTemplateUseCase implements UseCase<CreateTemplateInput, TemplateInfoDTO> {
    constructor(
        private readonly _context: IRequestContext,
        private readonly _templatesRepository: ITemplatesRepository,
    ) { }

    public run = async (args: UseCaseArgs<CreateTemplateInput>): Promise<TemplateInfoDTO> => {
        const auth = this._context.get();
        const authIsAdmin = auth?.is_admin === true;

        if (!authIsAdmin) {
            throw new ActionNotAllowedException('Solo un administrador puede crear plantillas');
        }

        // id_template is never sent: the uuid is generated by the database
        // (gen_random_uuid) and the created row comes back carrying it.
        const created = await this._templatesRepository.create({
            name: args.data.name,
            subject: args.data.subject,
            template: args.data.template,
            is_active: args.data.is_active ?? true,
        });

        return TemplateMapper.mapTemplate(created);
    };
}
